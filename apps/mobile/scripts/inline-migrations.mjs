// Inlines drizzle-kit's generated migrations (./drizzle/*.sql + journal)
// into a plain TypeScript module. Metro cannot import .sql files as raw
// text, so the app consumes the inlined strings through the drizzle expo
// migrator (`migrate(db, migrations)`); `npm run db:generate` refreshes it.
//
// Usage: node scripts/inline-migrations.mjs (from apps/mobile, after
// `drizzle-kit generate`).

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const migrationsDir = path.join(appRoot, 'drizzle')
const outFile = path.join(appRoot, 'src/shared/lib/db/migrations.generated.ts')

const journal = JSON.parse(readFileSync(path.join(migrationsDir, 'meta/_journal.json'), 'utf8'))

const migrations = {}
for (const entry of journal.entries) {
  const key = `m${String(entry.idx).padStart(4, '0')}`
  const sql = readFileSync(path.join(migrationsDir, `${entry.tag}.sql`), 'utf8')
  migrations[key] = sql
}

const files = readdirSync(migrationsDir).length
const body = `// GENERATED by scripts/inline-migrations.mjs from ./drizzle - DO NOT EDIT.
// Regenerate with \`pnpm db:generate\` after changing src/shared/lib/db/schema.ts.

export const migrations = ${JSON.stringify({ journal, migrations }, null, 2)}
`

writeFileSync(outFile, body)
console.log(`Inlined ${journal.entries.length} migration(s) (${files} files scanned) -> ${path.relative(appRoot, outFile)}`)
